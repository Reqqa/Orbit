def render(template_id: str, language: str, **values: object) -> str:
    """Render a pre-approved template; unknown languages fall back to EN."""
    variants = TEMPLATES[template_id]  # KeyError on an unknown template id, by design
    body = variants.get((language or "").upper(), variants[DEFAULT_LANGUAGE])
    try:
        return body.format(**values)
    except KeyError as exc:
        raise ValueError(
            f"template {template_id} ({language}) needs a value for {exc.args[0]!r}"
        ) from exc
